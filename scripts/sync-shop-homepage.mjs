import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";
import { format } from "prettier";

const SOURCE_URL = "https://leatherworship.com/";
const OUTPUT_URL = new URL("../src/lib/fourthwall/homepage.generated.ts", import.meta.url);

function productSlug(href) {
  if (!href) return null;
  const match = new URL(href, SOURCE_URL).pathname.match(/^\/products\/([^/]+)\/?$/);
  return match?.[1] ? decodeURIComponent(match[1]) : null;
}

function uniqueProductSlugs(section) {
  return Array.from(
    new Set(
      Array.from(section.querySelectorAll('a[href*="/products/"]'))
        .map((link) => productSlug(link.getAttribute("href")))
        .filter(Boolean),
    ),
  );
}

export function parseShopHomepage(html) {
  const document = new JSDOM(html, { url: SOURCE_URL }).window.document;
  const sections = Array.from(document.querySelectorAll(".main__sections > .fw-section"));
  const modules = [];

  for (const section of sections) {
    const id = section.id;
    const title = section.querySelector("h1, h2, h3")?.textContent?.trim().replace(/\s+/g, " ");

    if (id.includes("featured-collection")) {
      const productSlugs = uniqueProductSlugs(section);
      if (title && productSlugs.length > 0) {
        modules.push({ id, type: "collection", title, productSlugs });
      }
      continue;
    }

    if (id.includes("featured-product")) {
      const [featuredProductSlug] = uniqueProductSlugs(section);
      if (featuredProductSlug) {
        modules.push({ id, type: "product", productSlug: featuredProductSlug });
      }
      continue;
    }

    if (id.includes("image-with-text") && title && /commission/i.test(title)) {
      modules.push({ id, type: "commission" });
    }
  }

  if (!modules.some((module) => module.type === "collection")) {
    throw new Error("No Fourthwall collection modules were found.");
  }

  return { sourceUrl: SOURCE_URL, modules };
}

async function generatedSource(snapshot) {
  return format(
    `/* This file is generated by scripts/sync-shop-homepage.mjs. */

import type { SyncedShopHomepage } from "./homepage";

export const leatherWorshipHomepage = ${JSON.stringify(snapshot, null, 2)} satisfies SyncedShopHomepage;
`,
    { parser: "typescript" },
  );
}

async function syncShopHomepage() {
  const response = await fetch(SOURCE_URL, {
    headers: { "User-Agent": "DepartmentOfConsentShopSync/1.0" },
    signal: AbortSignal.timeout(15_000),
  });
  if (!response.ok) throw new Error(`Leather Worship returned HTTP ${response.status}.`);

  const snapshot = parseShopHomepage(await response.text());
  const nextSource = await generatedSource(snapshot);
  const currentSource = await readFile(OUTPUT_URL, "utf8").catch(() => "");

  if (nextSource === currentSource) {
    console.log("Leather Worship homepage modules are already current.");
    return;
  }

  await writeFile(OUTPUT_URL, nextSource, "utf8");
  console.log(`Synced ${snapshot.modules.length} Leather Worship homepage modules.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  syncShopHomepage().catch((error) => {
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`Leather Worship homepage sync skipped: ${message}`);
    console.warn("Using the last generated homepage snapshot.");
  });
}
